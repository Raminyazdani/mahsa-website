      repository_url: nullableText,
      correspondent: text,
      supervisors: nullableTexts,
      institution: nullableText,
      faculty: nullableText,
      school: nullableText,
      isbn: nullableText,
      submissionDate: nullableText,
      identifiers: { $ref: '#/definitions/publicationIdentifiers' },
      notes: nullableText,
      URL: nullableText,
      type_key: texts,
      status_verified_at: text,
      known_coauthors: texts,
      author_order_verified: flag,
      corresponding_author: text,
      _verification: provenance,
      page_count: integer,
      chapter_number: integer,
      isbn_ebook: text,
