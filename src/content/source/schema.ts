/**
 * Draft-07 structural schema for the user's supplied CV format.
 * Source-specific names and nesting belong only in this boundary.
 * Values are intentionally not restricted to the exemplar person's facts.
 */
const text = { type: 'string' };
const nullableText = { type: ['string', 'null'] };
const numberOrNull = { type: ['number', 'null'] };
const integerOrNull = { type: ['integer', 'null'] };
const texts = { type: 'array', items: text };
const nullableTexts = { type: ['array', 'null'], items: text };
const flag = { type: 'boolean' };
const integer = { type: 'integer' };
const provenance = {};

function object(
  properties: Record<string, unknown>,
  required: string[] = Object.keys(properties),
) {
  return { type: 'object', properties, required, additionalProperties: false };
}

function list(definition: string) {
  return { type: 'array', items: { $ref: `#/definitions/${definition}` } };
}

